// Build src/sets.js: the Set builder's categories and target colors, from the community hex sheet
// https://docs.google.com/spreadsheets/d/1MuBide8AJzDYoF62G3h7F6_1u4GvouvIm9RMXMH-pPc (one tab per category).
// Usage: node tools/build_sets.js
const fs = require('fs'), path = require('path');
const DOC = 'https://docs.google.com/spreadsheets/d/1MuBide8AJzDYoF62G3h7F6_1u4GvouvIm9RMXMH-pPc';
const csvRows = (t) => t.split(/\r?\n/).map((l) => { const out = []; let cur = '', q = false; for (const ch of l) { if (ch === '"') q = !q; else if (ch === ',' && !q) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out; });
(async () => {
  const html = await (await fetch(DOC + '/htmlview')).text();
  const tabs = [...html.matchAll(/\{name: "([^"]+)", pageUrl: "[^"]*", gid: "(\d+)"/g)].map((m) => [m[1], m[2]]).filter(([n]) => !/^ALL/i.test(n));
  const cats = [];
  for (const [name, gid] of tabs) {
    const rows = csvRows(await (await fetch(`${DOC}/export?format=csv&gid=${gid}`)).text());
    const items = rows.filter((r) => r[0] && /^#[0-9A-Fa-f]{6}$/.test((r[1] || '').trim())).map((r) => [r[0].trim(), r[1].trim().slice(1).toUpperCase()]);
    if (items.length) cats.push([name, items]);
  }
  fs.writeFileSync(path.join(__dirname, '../src/sets.js'), `// Generated by tools/build_sets.js from the community hex sheet:\n// ${DOC}\nconst SET_CATS = ${JSON.stringify(cats)};\n`);
  console.log(cats.map(([n, i]) => `${n} (${i.length})`).join(', '));
})();
