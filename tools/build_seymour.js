// Build src/seymour.js: the leather armor target colors and fade dyes of SeymourAnalyzer
// (GPL-3, https://github.com/Schnerry/SeymourAnalyzerFabric, originally the CT module by AllyMeSB).
// Usage: node tools/build_seymour.js
const fs = require('fs'), path = require('path');
const URL = 'https://raw.githubusercontent.com/Schnerry/SeymourAnalyzerFabric/main/src/main/resources/data/seymouranalyzer/colors.json';
(async () => {
  const j = await (await fetch(URL)).json();
  const hexes = (m) => Object.fromEntries(Object.entries(m).filter(([, h]) => /^[0-9A-F]{6}$/i.test(h)).map(([n, h]) => [n, h.toUpperCase()]));
  const t = hexes(j.TARGET_COLORS), f = hexes(j.FADE_DYES);
  fs.writeFileSync(path.join(__dirname, '../src/seymour.js'), '// Generated by tools/build_seymour.js from SeymourAnalyzer colors.json (GPL-3).\n'
    + 'const SEY_TARGETS = ' + JSON.stringify(t) + ';\nconst SEY_FADES = ' + JSON.stringify(f) + ';\n');
  console.log(Object.keys(t).length, 'targets,', Object.keys(f).length, 'fades');
})();
