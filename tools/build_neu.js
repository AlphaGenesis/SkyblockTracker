// Build src/neu.js from the same NEU-REPO snapshot as items.js (run right after tools/build_items.py):
//   NEU_IDS     every NEU item id already in items.js, so the app only fetches items added to NEU later
//   MODEL_ICONS vanilla model ("minecraft:paper") -> bundled icon in src/items/, for those later items
// Usage: node tools/build_neu.js <NEU-REPO items dir>
const fs = require('fs'), path = require('path');
const neu = process.argv[2], src = path.join(__dirname, '../src');
const ITEMS = new Function(fs.readFileSync(path.join(src, 'items.js'), 'utf8') + '; return ITEMS;')();
const fileOf = new Map(ITEMS.map(([n, f]) => [n.toLowerCase(), f]));
const ids = [], icons = {};
for (const f of fs.readdirSync(neu).sort()) {
  if (!f.endsWith('.json')) continue;
  ids.push(f.slice(0, -5));
  let j;
  try { j = JSON.parse(fs.readFileSync(path.join(neu, f), 'utf8')); } catch { continue; }
  const nbt = j.nbttag || '', m = (nbt.match(/ItemModel:"([^"]+)"/) || [])[1] || '';
  const file = fileOf.get(String(j.displayname || '').replace(/§.|[-]/g, '').trim().toLowerCase());
  if (m.startsWith('minecraft:') && !/SkullOwner|color:/.test(nbt) && file && !icons[m]) icons[m] = file; // plain Minecraft texture
}
fs.writeFileSync(path.join(src, 'neu.js'), '// Generated by tools/build_neu.js from the NEU-REPO snapshot of items.js.\n'
  + 'const NEU_IDS = ' + JSON.stringify(ids.join(',')) + ';\nconst MODEL_ICONS = ' + JSON.stringify(icons) + ';\n');
console.log(ids.length, 'ids,', Object.keys(icons).length, 'models');
